function syncMessage(request: SigningRequest, message: Message) {
  const metadata = record(request.venue_metadata), built = record(metadata.built), manifest = record(built.manifest)
  const bytes = message.serialize(), message_base64 = bytes.toString('base64'), message_sha256 = createHash('sha256').update(bytes).digest('hex')
  Object.assign(record(request.unsigned_payload), { message_base64, message_sha256 })
  Object.assign(built, { message_base64, message_sha256, recent_blockhash: message.recentBlockhash })
  manifest.account_keys = message.accountKeys.map((key, index) => ({ index, pubkey: key.toBase58(), signer: index < message.header.numRequiredSignatures, writable: message.isAccountWritable(index) }))
  manifest.instructions = message.instructions.map((ix) => ({ program_id: message.accountKeys[ix.programIdIndex].toBase58(), program_id_index: ix.programIdIndex, account_indexes: ix.accounts, data_base64: Buffer.from(bs58.decode(ix.data)).toString('base64') }))
}

