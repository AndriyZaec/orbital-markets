function mutateBytes(request: SigningRequest, change: (message: Message, data: Uint8Array) => void) {
  const message = Message.from(Buffer.from(String(record(request.unsigned_payload).message_base64), 'base64'))
  const data = bs58.decode(message.instructions[2].data)
  change(message, data)
  message.instructions[2].data = bs58.encode(data)
  syncMessage(request, message) // Rehash/update the diagnostic manifest too.
}

test('stored Phoenix agent signs exact pinned native and Flight bytes, preserving u64 CID', async () => {
  const storage = new TestTradingAgentStore()
  await storage.save(agent)
  for (const flight of [false, true]) {
    const request = fixture(flight)
    const signed = await signWithStoredTradingAgent(storage, request)
    assert.equal(signed.client_order_id, '18446744073709551615')
    assert.equal(signed.signer_address, address)
    assert.equal(nacl.sign.detached.verify(Buffer.from(String(record(request.unsigned_payload).message_base64), 'base64'), bs58.decode(signed.signature), bs58.decode(address)), true)
  }
})

test('close and emergency-close enforce reduce-only and allow sell IOC', async () => {
  for (const flight of [false, true]) {
    const request = fixture(flight), metadata = record(request.venue_metadata)
    request.action = flight ? 'close' : 'emergency_close'; request.side = 'sell'; request.reduce_only = true
    Object.assign(record(record(metadata.built).manifest), { intent_action: request.action, side: 'ask', reduce_only: true })
    record(metadata.normalized).side = 'ask'
    mutateBytes(request, (_, data) => { data[(flight ? 8 : 0) + 9] = 1; data[(flight ? 8 : 0) + 71] = 128 })
    await signPhoenixAgentRequest(request, agent)
  }
})

test('changing native packet semantics fails even with a matching digest and manifest', async () => {
  for (const flight of [false, true]) {
    // Side, price, size, self-trade, low/high CID bytes, slot, flags, cancellation.
    for (const offset of [9, 11, 19, 44, 46, 54, 63, 71, 72]) {
      const request = fixture(flight)
      mutateBytes(request, (_, data) => { data[(flight ? 8 : 0) + offset] ^= 1 })
      await assert.rejects(signPhoenixAgentRequest(request, agent), /bounded IOC/)
    }
  }
})

